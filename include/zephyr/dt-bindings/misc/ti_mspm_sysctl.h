#ifndef ZEPHYR_INCLUDE_DT_BINDINGS_MISC_TI_MSPM_SYSCTL_H_
#define ZEPHYR_INCLUDE_DT_BINDINGS_MISC_TI_MSPM_SYSCTL_H_

/* SYSCTL.PWREN_MCPERIPH register offset from SYSCTL base (0x400AF000) */
#define MSPM_SYSCTL_PWREN_MCPERIPH 0x1424

/* SYSCTL.RSTCTL_*_MCPERIPH — same bit index as PWREN_MCPERIPH */
#define MSPM_SYSCTL_RSTCTL_ASSERT_MCPERIPH 0x1428
#define MSPM_SYSCTL_RSTCTL_CLEAR_MCPERIPH  0x142C

/* PWREN_MCPERIPH bit indices */
#define MSPM_SYSCTL_PWREN_EQEP0_BIT 0
#define MSPM_SYSCTL_PWREN_EQEP1_BIT 1
#define MSPM_SYSCTL_PWREN_EQEP2_BIT 2
#define MSPM_SYSCTL_PWREN_ECAP0_BIT 3
#define MSPM_SYSCTL_PWREN_ECAP1_BIT 4
#define MSPM_SYSCTL_PWREN_PWM0_BIT  5
#define MSPM_SYSCTL_PWREN_PWM1_BIT  6
#define MSPM_SYSCTL_PWREN_PWM2_BIT  7
#define MSPM_SYSCTL_PWREN_PWM3_BIT  8
#define MSPM_SYSCTL_PWREN_PWM4_BIT  9
#define MSPM_SYSCTL_PWREN_XBAR_BIT  14

/* SYSCTL.PERCLKCR — global MCPWM TBCLK sync */
#define MSPM_SYSCTL_PERCLKCR       0x148C
#define MSPM_SYSCTL_TBCLKSYNC_BIT  0

#endif /* ZEPHYR_INCLUDE_DT_BINDINGS_MISC_TI_MSPM_SYSCTL_H_ */
